/**
 * A synthetic hospital formulary for hms_dev, so the pharmacy has a realistic range of
 * medicines: about 150 products in 15 therapeutic classes, in every dosage form the schema
 * allows (tablets, capsules, syrups, suspensions, injections, IV fluids, creams, ointments,
 * gels, drops, inhalers, powders, solutions).
 *
 * Ingredients and strengths are ordinary generic names and common strengths so the catalogue
 * reads like a real pharmacy; every brand name ("Demo …"), manufacturer, price, batch and
 * expiry is invented. Nothing here is a clinical recommendation.
 *
 * Opening stock goes through the real paths: a goods receipt into the General Store by the
 * demo inventory user (inv1), then a transfer of half of each item to the Main Pharmacy,
 * received by the demo pharmacist (pha1), so every unit has a movement. A few items are
 * deliberately near expiry or below their reorder level so those warnings can be seen.
 *
 * Needs the demo catalogue first (db:seed:demo:catalogue: locations) and the demo accounts
 * (db:seed:demo: inv1, pha1). Safe to re-run: products are added only when their SKU is
 * missing, nothing is updated or deleted, and stock is received only for formulary items
 * that have no batch yet. One audit row with counts when something was added.
 */
