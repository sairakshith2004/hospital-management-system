/** The formulary, flattened (general classes, then the specialty classes). */
export const FORMULARY: FormularyProduct[] = Object.entries({
  ...CLASSES,
  ...SPECIALTY_CLASSES,
}).flatMap(([category, rows]) =>
  rows.map(([sku, brand, form, route, unit, composition, price, packSize, rxOnly, stock]) => ({
    sku,
    brand,
    form,
    route,
    unit,
    composition,
    price,
    packSize,
    rxOnly: rxOnly ?? true,
    category,
    ...(stock ? { stock } : {}),
  })),
);

/** "amoxicillin 500 mg + clavulanic acid 125 mg" → [[name, value, unit], …] */
export function parseComposition(text: string): [string, number, string][] {
  return text.split(' + ').map((part) => {
    const m = /^(.+) (\d+(?:\.\d+)?) ?(\S+)$/.exec(part.trim());
    if (!m || !(STRENGTH_UNITS as readonly string[]).includes(m[3]!)) {
      throw new Error(`Formulary composition not understood: "${part}"`);
    }
    return [m[1]!, Number(m[2]), m[3]!];
  });
}

/** Default stock per dispensing unit: enough for a demo, never a real forecast. */
function stockFor(
  p: FormularyProduct,
  index: number,
): { qty: number; expiryDays: number; reorderLevel: number } {
  const base: Record<string, [number, number]> = {
    tablet: [600, 100],
    capsule: [400, 80],
    ml: [3000, 500],
    sachet: [200, 40],
  };
  const [qty, reorderLevel] = base[p.unit] ?? [60, 10];
  return {
    qty: p.stock?.qty ?? qty,
    reorderLevel: p.stock?.reorderLevel ?? reorderLevel,
    // Spread expiries over roughly 6–30 months.
    expiryDays: p.stock?.expiryDays ?? 180 + ((index * 37) % 720),
  };
}

export interface DemoFormularyResult {
  ingredients: number;
  products: number;
  supplier: number;
  stockedItems: number;
  batches: number;
}

async function userByName(db: Queryable, username: string): Promise<string | null> {
  const { rows } = await db.query<{ id: string }>(
    "SELECT id FROM users WHERE username = $1 AND status = 'active'",
    [username],
  );
  return rows[0]?.id ?? null;
}

export async function seedDemoFormulary(db: Queryable): Promise<DemoFormularyResult> {
  await db.query('SELECT pg_advisory_xact_lock($1)', [LOCK]);
  const r: DemoFormularyResult = {
    ingredients: 0,
    products: 0,
    supplier: 0,
    stockedItems: 0,
    batches: 0,
  };

  const { rows: loc } = await db.query<{ code: string; id: string }>(
    `SELECT code, id FROM locations WHERE code IN ('GEN-STORE', 'MAIN-PHARM')`,
  );
  const store = loc.find((l) => l.code === 'GEN-STORE')?.id;
  const pharmacy = loc.find((l) => l.code === 'MAIN-PHARM')?.id;
  if (!store || !pharmacy) {
    throw new Error(
      'Run db:seed:demo:catalogue first: the General Store and Main Pharmacy are missing.',
    );
  }

  for (const p of FORMULARY) {
    const parts = parseComposition(p.composition);
    for (const [name] of parts) {
      r.ingredients +=
        (
          await db.query(
            'INSERT INTO ingredients (name) VALUES ($1) ON CONFLICT (name) DO NOTHING',
            [name],
          )
        ).rowCount ?? 0;
    }
    const strengths = parts.map(([, v, u]) => `${v} ${u}`).join(' + ');
    const { reorderLevel } = stockFor(p, 0);
    const { rows } = await db.query<{ id: string }>(
      `INSERT INTO stock_items (sku, kind, name, base_unit, category, reorder_level, tracks_expiry)
       VALUES ($1, 'medicine', $2, $3, $4, $5, true) ON CONFLICT (sku) DO NOTHING RETURNING id`,
      [p.sku, `${p.brand} ${strengths} ${p.form}`, p.unit, p.category, reorderLevel],
    );
    if (!rows[0]) continue;
    r.products += 1;
    await db.query(
      `INSERT INTO medicine_products (stock_item_id, brand_name, manufacturer, dosage_form, route, pack_size, rx_only)
       VALUES ($1, $2, 'Demo Pharma (synthetic)', $3, $4, $5, $6)`,
      [rows[0].id, p.brand, p.form, p.route, p.packSize, p.rxOnly],
    );
    for (const [name, value, unit] of parts) {
      await db.query(
        `INSERT INTO product_ingredients (product_id, ingredient_id, strength_value, strength_unit)
         SELECT $1, id, $3, $4 FROM ingredients WHERE name = $2`,
        [rows[0].id, name, value, unit],
      );
    }
  }

  r.supplier +=
    (
      await db.query(
        'INSERT INTO suppliers (code, name, phone) VALUES ($1, $2, $3) ON CONFLICT (code) DO NOTHING',
        [FORMULARY_SUPPLIER.code, FORMULARY_SUPPLIER.name, FORMULARY_SUPPLIER.phone],
      )
    ).rowCount ?? 0;

  // Opening stock for formulary items that have no batch yet: receipt by inv1, transfer by pha1.
  const inv = await userByName(db, 'inv1');
  const pha = await userByName(db, 'pha1');
  const { rows: unstocked } = await db.query<{ id: string; sku: string }>(
    `SELECT s.id, s.sku FROM stock_items s
      WHERE s.sku LIKE $1 AND NOT EXISTS (SELECT 1 FROM stock_batches b WHERE b.stock_item_id = s.id)
      ORDER BY s.sku`,
    [`${FORMULARY_PREFIX}%`],
  );
  if (unstocked.length > 0 && inv && pha) {
    const { rows: grn } = await db.query<{ id: string }>(
      `INSERT INTO goods_receipts (supplier_id, location_id, supplier_invoice_ref, received_by)
       SELECT id, $1, $2, $3 FROM suppliers WHERE code = $4 RETURNING id`,
      [store, FORMULARY_GRN_REF, inv, FORMULARY_SUPPLIER.code],
    );
    const { rows: tr } = await db.query<{ id: string }>(
      `INSERT INTO stock_transfers (from_location_id, to_location_id, reason, dispatched_by)
       VALUES ($1, $2, 'Demo formulary opening stock', $3) RETURNING id`,
      [store, pharmacy, inv],
    );
    for (const item of unstocked) {
      const index = FORMULARY.findIndex((p) => p.sku === item.sku);
      const product = FORMULARY[index];
      if (!product) continue; // a DF- item that is no longer in the list: leave it alone
      const { qty, expiryDays } = stockFor(product, index);
      const price = product.price;
      const batchNo = `DF${String(index + 1).padStart(4, '0')}`;
      const { rows: b } = await db.query<{ id: string }>(
        `INSERT INTO stock_batches (stock_item_id, location_id, batch_no, expiry_date, unit_cost_paise, sale_price_paise, qty_on_hand, created_by, updated_by)
         VALUES ($1, $2, $3, (now() AT TIME ZONE 'Asia/Kolkata')::date + $4::int, $5, $6, $7, $8, $8) RETURNING id`,
        [item.id, store, batchNo, expiryDays, Math.round(price * 0.6), price, qty, inv],
      );
      const { rows: mv } = await db.query<{ id: number }>(
        `INSERT INTO stock_movements (batch_id, location_id, kind, qty, balance_after, ref_type, ref_id, performed_by)
         VALUES ($1, $2, 'receipt', $3, $3, 'goods_receipt', $4, $5) RETURNING id::int`,
        [b[0]!.id, store, qty, grn[0]!.id, inv],
      );
      await db.query(
        `INSERT INTO grn_lines (grn_id, stock_item_id, batch_no, expiry_date, qty, unit_cost_paise, batch_id, stock_movement_id)
         SELECT $1, stock_item_id, batch_no, expiry_date, $2, unit_cost_paise, id, $3 FROM stock_batches WHERE id = $4`,
        [grn[0]!.id, qty, mv[0]!.id, b[0]!.id],
      );
      // Half of each item moves to the pharmacy.
      const half = Math.floor(qty / 2);
      await db.query('UPDATE stock_batches SET qty_on_hand = qty_on_hand - $2 WHERE id = $1', [
        b[0]!.id,
        half,
      ]);
      const { rows: out } = await db.query<{ id: number }>(
        `INSERT INTO stock_movements (batch_id, location_id, kind, qty, balance_after, ref_type, ref_id, performed_by)
         VALUES ($1, $2, 'transfer_out', $3, $4, 'stock_transfer', $5, $6) RETURNING id::int`,
        [b[0]!.id, store, -half, qty - half, tr[0]!.id, inv],
      );
      const { rows: pb } = await db.query<{ id: string }>(
        `INSERT INTO stock_batches (stock_item_id, location_id, batch_no, expiry_date, unit_cost_paise, sale_price_paise, qty_on_hand, created_by, updated_by)
         SELECT stock_item_id, $2, batch_no, expiry_date, unit_cost_paise, sale_price_paise, $3, $4, $4 FROM stock_batches WHERE id = $1 RETURNING id`,
        [b[0]!.id, pharmacy, half, pha],
      );
      const { rows: inn } = await db.query<{ id: number }>(
        `INSERT INTO stock_movements (batch_id, location_id, kind, qty, balance_after, ref_type, ref_id, performed_by)
         VALUES ($1, $2, 'transfer_in', $3, $3, 'stock_transfer', $4, $5) RETURNING id::int`,
        [pb[0]!.id, pharmacy, half, tr[0]!.id, pha],
      );
      await db.query(
        `INSERT INTO stock_transfer_lines (transfer_id, from_location_id, to_location_id, stock_item_id, from_batch_id, to_batch_id, qty, out_movement_id, in_movement_id)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)`,
        [tr[0]!.id, store, pharmacy, item.id, b[0]!.id, pb[0]!.id, half, out[0]!.id, inn[0]!.id],
      );
      r.stockedItems += 1;
      r.batches += 2;
    }
    await db.query(
      `UPDATE stock_transfers SET status = 'received', received_by = $2, received_at = now() WHERE id = $1`,
      [tr[0]!.id, pha],
    );
  }

  if (Object.values(r).some((v) => v > 0)) {
    await recordAudit(
      db,
      {
        actor: SYSTEM,
        action: 'demo_seed.formulary_applied',
        entityType: 'system',
        changes: { ...r },
      },
      { requestId: null, ip: null },
    );
  }
  return r;
}
